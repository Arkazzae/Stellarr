/**
 * Build the icon family from `src/icons/source/glyphs.ts`:
 *
 * - `src/icons/paths.ts`, the static table the apps import;
 * - `branding/icons/linear/*.svg` and `branding/icons/broken/*.svg`.
 *
 *   node scripts/build-icons.mjs           write both
 *   node scripts/build-icons.mjs --check   fail if either is out of date
 *   node scripts/build-icons.mjs --audit   list strokes closer than the spacing rule
 */
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";

import { CLEAR, samples } from "../src/icons/source/geometry.ts";
import { GLYPHS } from "../src/icons/source/glyphs.ts";

const VARIANTS = ["linear", "broken"];
const check = process.argv.includes("--check");
const audit = process.argv.includes("--audit");
const table = new URL("../src/icons/paths.ts", import.meta.url);
const branding = new URL("../../../branding/icons/", import.meta.url);

const strokes = (name, variant) => GLYPHS[name].map((s) => (typeof s === "string" ? s : s[variant]));
const names = Object.keys(GLYPHS);
const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

// ── The table ──
const list = (paths) => `[\n${paths.map((d) => `      ${JSON.stringify(d)},`).join("\n")}\n    ]`;
const entries = names.map((name) => {
  const linear = strokes(name, "linear");
  const broken = strokes(name, "broken");
  const same = linear.join("\n") === broken.join("\n");
  return `  ${name}: {\n    linear: ${list(linear)},${same ? "" : `\n    broken: ${list(broken)},`}\n  },`;
});
const source = `/**
 * Generated by \`npm run icons:build -w @stellarr/ui\` from \`source/glyphs.ts\`.
 * Do not edit by hand: change the source and run the build.
 */
export type IconPath = string;

/** linear: closed, continuous contours; broken: the same contours, each main one opened once. */
export type IconVariant = "linear" | "broken";

/** Both variants of a glyph; \`broken\` is left out where it is the same as \`linear\`. */
export interface IconGlyph {
  readonly linear: readonly IconPath[];
  readonly broken?: readonly IconPath[];
}

export const ICON_GLYPHS = {
${entries.join("\n")}
} as const satisfies Record<string, IconGlyph>;

export type IconName = keyof typeof ICON_GLYPHS;

export const ICON_VARIANTS: readonly IconVariant[] = ["linear", "broken"];

/** The strokes of one glyph in one variant. */
export function iconPaths(name: IconName, variant: IconVariant): readonly IconPath[] {
  const glyph: IconGlyph = ICON_GLYPHS[name];
  return (variant === "broken" ? glyph.broken : undefined) ?? glyph.linear;
}
`;

// ── The SVG files ──
const svg = (name, variant) =>
  [
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">',
    `  <title>${name.replace(/([a-z0-9])([A-Z])/g, "$1 $2")}</title>`,
    ...strokes(name, variant).map((d) => `  <path d="${d}"/>`),
    "</svg>",
    "",
  ].join("\n");
const files = new Map();
for (const variant of VARIANTS) for (const name of names) files.set(`${variant}/${kebab(name)}.svg`, svg(name, variant));

const listSvgs = async (dir) =>
  (await readdir(new URL(dir, branding)).catch(() => [])).filter((f) => f.endsWith(".svg")).map((f) => (dir ? `${dir}${f}` : f));
const existing = [...(await listSvgs("")), ...(await listSvgs("linear/")), ...(await listSvgs("broken/"))];
const stale = existing.filter((f) => !files.has(f));

if (check) {
  const problems = [];
  if ((await readFile(table, "utf8").catch(() => null)) !== source) problems.push("src/icons/paths.ts");
  for (const [file, text] of files) {
    if ((await readFile(new URL(file, branding), "utf8").catch(() => null)) !== text) problems.push(`branding/icons/${file}`);
  }
  for (const file of stale) problems.push(`branding/icons/${file} (no longer in the family)`);
  if (problems.length) {
    throw new Error(`Icons need building (npm run icons:build -w @stellarr/ui):\n  ${problems.slice(0, 20).join("\n  ")}${problems.length > 20 ? `\n  …and ${problems.length - 20} more` : ""}`);
  }
  console.log(`[icons] Verified ${names.length} glyphs, paths.ts and ${files.size} SVG files.`);
} else {
  await writeFile(table, source);
  for (const variant of VARIANTS) await mkdir(new URL(`${variant}/`, branding), { recursive: true });
  for (const [file, text] of files) await writeFile(new URL(file, branding), text);
  for (const file of stale) await rm(new URL(file, branding));
  console.log(`[icons] Built ${names.length} glyphs: paths.ts and ${files.size} SVG files${stale.length ? `, removed ${stale.length} old ones` : ""}.`);
}

// ── Spacing audit: separate strokes either join or keep CLEAR apart, centre to centre ──
if (audit) {
  const segDist = (p, a, b) => {
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const l2 = dx * dx + dy * dy;
    const t = l2 ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / l2)) : 0;
    return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dy));
  };
  const tight = [];
  for (const name of names) {
    const parts = strokes(name, "linear").flatMap((d) => samples(d, 24));
    let worst = Infinity;
    for (let i = 0; i < parts.length; i++)
      for (let j = i + 1; j < parts.length; j++) {
        // Strokes that touch are joined on purpose; only gaps between separate strokes count.
        let pair = Infinity;
        for (const p of parts[i])
          for (let k = 0; k < parts[j].length; k++) {
            const d = k === 0 ? Math.hypot(p[0] - parts[j][0][0], p[1] - parts[j][0][1]) : segDist(p, parts[j][k - 1], parts[j][k]);
            if (d < pair) pair = d;
          }
        if (pair > 0.4 && pair < worst) worst = pair;
      }
    // Sampling the curves costs up to about 0.15 of accuracy.
    if (worst < CLEAR - 0.15) tight.push(`${name} ${worst.toFixed(2)}`);
  }
  console.log(tight.length ? `[icons] Closer than ${CLEAR} between separate strokes: ${tight.join(", ")}` : `[icons] Every glyph keeps ${CLEAR} between separate strokes.`);
}
