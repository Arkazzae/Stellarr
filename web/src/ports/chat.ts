export type Unsubscribe = () => void;

/**
 * Everything the text view is allowed to do.
 *
 * Components are written against this rather than the HTTP client or the
 * SignalR hub, so a change of transport stays under `src/adapters/`.
 */
export interface ChatPort {
  /** Newest last. The opaque cursor pages backwards through one snapshot. */
  listMessages(
    channelId: ChannelId,
    options?: { cursor?: string; limit?: number },
  ): Promise<MessageHistoryPage>;
  /** Durable catch-up for mutations missed while SignalR was disconnected. */
  syncMessages(channelId: ChannelId, after: string): Promise<MessageSyncPage>;
  /** All threads in a channel, newest activity first. */
  listThreads(channelId: ChannelId): Promise<ThreadSummary[]>;
  /** Root plus every reply, even when the transcript has not loaded them. */
  getThread(channelId: ChannelId, rootId: MessageId): Promise<Message[]>;
  /** Complete server-side channel catalogue, independent of loaded history. */
  listIndexed(
    channelId: ChannelId,
    options: {
      kind: MessageIndexKind;
      query?: string;
      cursor?: string;
      limit?: number;
    },
  ): Promise<MessageIndexPage>;
  /** Compatibility search over the full channel index. */
  search(channelId: ChannelId, query: string): Promise<Message[]>;

  /**
   * The channel's pinned messages, newest pin first.
   *
   * A read of its own, not a filter over `listMessages`: a pin usually sits
   * far above the loaded window, so a derived list would grow as you scroll.
   */
  listPinned(channelId: ChannelId): Promise<Message[]>;

  send(input: SendMessage): Promise<Message>;

  /** Uploads and returns the attachment to reference in `send`. */
  uploadAttachment(
    file: File,
    options?: { voiceMessage?: boolean; durationSeconds?: number },
  ): Promise<Attachment>;

  /** Fires for every channel; filter by `message.channelId`. */
  onMessage(handler: (message: Message) => void): Unsubscribe;

  /**
   * Fires when a message is rewritten. Carries the whole message rather than
   * a patch, so a client that missed an earlier edit still ends up current.
   */
  onMessageUpdated(handler: (message: Message) => void): Unsubscribe;

  /** Fires when a message is removed. Only the ids survive it. */
  onMessageDeleted(handler: (deleted: MessageDeleted) => void): Unsubscribe;

  /**
   * Fires when a message's links finish unfurling, always after the message
   * itself: the server reads the linked page in the background instead of
   * making the sender wait.
   */
  onEmbedsUpdated(handler: (update: MessageEmbedsUpdate) => void): Unsubscribe;

  /**
   * For servers that still need an explicit channel group; current ones push
   * every text channel to the shared server group. Safe to repeat.
   */
  focusChannel(channelId: ChannelId): Promise<void>;

  /** Durable read watermarks for the signed-in user. */
  getReadState(): Readonly<Record<ChannelId, string>>;
  markChannelRead(channelId: ChannelId): Promise<void>;
  onChannelReadChanged(
    handler: (channelId: ChannelId, lastReadAt: string) => void,
  ): Unsubscribe;
  dispose?(): void;
}

export interface SendMessage {
  channelId: ChannelId;
  content: string;
  attachmentIds: string[];
  /** Stable idempotency key generated by the composer. */
  clientMessageId: MessageId;
  /** The message being answered, when this is a reply. */
  replyToMessageId?: MessageId;
}

/** Message mutations, kept apart from transcript loading and delivery. */
export interface MessageActionsPort {
  react(messageId: MessageId, emoji: string): Promise<void>;
  unreact(messageId: MessageId, emoji: string): Promise<void>;
  edit(messageId: MessageId, content: string): Promise<void>;
  remove(messageId: MessageId): Promise<void>;
  /**
   * Pins or unpins in one call, because the toolbar has one control that reads
   * "Przypnij" or "Odepnij" depending on the message under it.
   */
  setPinned(messageId: MessageId, pinned: boolean): Promise<void>;
  /** What the transcript renders, keyed by message id. */
  onReactionsChanged(
    handler: (messageId: MessageId, reactions: Reaction[]) => void,
  ): Unsubscribe;
  getReactions(messageId: MessageId): Reaction[];
  dispose?(): void;
}

export type Reaction = MessageReaction;

/** Who is typing where, as the composer reports it. */
export interface TypingPort {
  /** Called on keystroke; the adapter throttles. */
  notifyTyping(channelId: ChannelId): void;
  onTypingChanged(
    handler: (channelId: ChannelId, displayNames: string[]) => void,
  ): Unsubscribe;
  dispose?(): void;
}
