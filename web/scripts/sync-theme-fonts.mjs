/**
 * Downloads the theme fonts from Google Fonts into `public/fonts` and rewrites
 * `src/styles/themes/font-faces.css` so every face is served from our own
 * origin. The results are committed; run this by hand (`npm run fonts:sync`)
 * only when the list below changes.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const FONT_DIR = fileURLToPath(new URL("../public/fonts", import.meta.url));
const CSS_FILE = fileURLToPath(
  new URL("../src/styles/themes/font-faces.css", import.meta.url),
);

// Google serves woff2 files only to a browser it recognises.
const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
  "(KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36";

const SUBSETS = new Set(["latin", "latin-ext"]);

/** [id used in file names, family name, Google Fonts query] */
const FONTS = [
  ["outfit", "Outfit", "Outfit:wght@100..900"],
  ["jetbrains-mono", "JetBrains Mono", "JetBrains+Mono:wght@100..800"],
];

async function fetchOk(url) {
  const response = await fetch(url, { headers: { "user-agent": USER_AGENT } });
  if (!response.ok) {
    throw new Error(`${response.status} ${response.statusText}: ${url}`);
  }
  return response;
}

/** Each @font-face block of a Google Fonts stylesheet with its subset label. */
function readFaces(css) {
  const pairs = css.matchAll(
    /\/\*\s*([^*]+?)\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/g,
  );
  return [...pairs].map(([, subset, face]) => ({ subset, face }));
}

function indent(text) {
  return text
    .split("\n")
    .map((line) => `  ${line}`)
    .join("\n");
}

async function syncFamily(id, family, query) {
  const url = `https://fonts.googleapis.com/css2?family=${query}&display=swap`;
  const faces = readFaces(await (await fetchOk(url)).text()).filter(
    ({ subset }) => SUBSETS.has(subset),
  );
  if (faces.length === 0) {
    throw new Error(`Google Fonts returned no latin subsets for ${family}`);
  }

  const blocks = [`  /* ${family} */`];
  for (const { subset, face } of faces) {
    const source = /src:\s*url\((https:\/\/[^)]+)\)/.exec(face)?.[1];
    const weight = /font-weight:\s*([^;]+);/.exec(face)?.[1]?.trim();
    if (source === undefined || weight === undefined) {
      throw new Error(`Could not parse ${family} (${subset})`);
    }
    const file = `${id}-${weight.replace(/\s+/g, "-")}-${subset}.woff2`;
    const bytes = Buffer.from(await (await fetchOk(source)).arrayBuffer());
    await writeFile(join(FONT_DIR, file), bytes);
    blocks.push(
      `  /* ${subset} */`,
      indent(face.replace(source, `/fonts/${file}`)),
    );
  }
  return blocks;
}

await mkdir(FONT_DIR, { recursive: true });

const lines = [
  "/* Generated by scripts/sync-theme-fonts.mjs. Do not edit by hand. */",
  "@layer base {",
];
for (const [id, family, query] of FONTS) {
  lines.push(...(await syncFamily(id, family, query)));
}
lines.push("}", "");

await writeFile(CSS_FILE, lines.join("\n"));
console.log(`Synced ${FONTS.length} families to ${FONT_DIR}`);
